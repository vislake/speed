#!/usr/bin/env python3
"""Coverage gate for every released module.

Every released Go module -- the 23 go.work entries: the 22 go/* modules
plus the reference app -- must hold its unit-suite statement coverage
at or above an 80% floor and must not let it decline against a recorded
baseline. This script is the mechanism behind that rule: collect (run
`go test -count=1 -coverpkg=./... -coverprofile` from the module
directory and compute the module's exact total statement coverage --
the module's unit suite measured against the whole module, a quantity
the "why" section below defines), store
(tools/coverage-baselines.json, committed, regenerated by --update),
compare (fail when the measured total breaches either bound), and
self-check the baseline file's own health (--selfcheck).

History of the rule. docs/internal/20-quality-and-security.md once drew
the no-uniform-threshold line (a percentage target "breeds meaningless
tests") and asked only that the six foundation modules -- pkgcore,
dbkit, tenancy, rbac, billing, jobs -- keep "coverage must not decline
(against a baseline)". This script shipped exactly that decline
mechanism for those six. The product decision changed in 2026-09: every
released module must hold at least 80% statement coverage, measured
excluding generated files. The no-uniform-threshold argument is
superseded for the lower bound by that decision (docs/internal/20
records the change); the decline gate survives unchanged, so coverage
that merely slides within a high-but-falling band still fails, and a
deliberate re-baseline stays possible above the floor.

Generated files. The quantity the gate compares excludes statements
whose profile path contains ".gen.go" -- the committed oapi-codegen
output every spec-carrying module and the reference app ship. Generated
code is written by a pinned generator, not by a human, so its statements
are not a meaningful test target: including them would let a generator
change (or a spec growing more error paths) move the measured total
independently of the module's hand-written code. The exclusion applies
at both ends -- --update stores exclusion-rule numbers and --check
compares them -- so the baseline file was re-recorded in the same change
that defined the rule: baseline records travel with the change that
defines the quantity.

Why statement coverage of the module's whole unit suite, compared per
module

  * The rule is per module and both floor- and baseline-relative, so
    the measured quantity is one comparable number per module: total
    covered statements / total statements over the module's own unit
    suite (`go test -count=1 -coverpkg=./... -coverprofile ... ./...`
    from the module directory), parsed exactly from the merged
    profile -- never the rounded `go tool cover -func` total, whose
    0.1-point rounding would blind the gate to every change smaller
    than a tenth of a point.
  * The measured quantity is the module suite against the whole
    module, not the per-package sums go test produces by default:
    -coverpkg=./... instruments every module package in every test
    binary, so a block any unit test executes counts toward the
    package it lives in, no matter which package the test runs from.
    Plain per-package instrumentation -- go test's default -- counts
    only what a package's own tests execute, and the unit-test layout
    deliberately puts whole suite classes into directories of their
    own (go/<module>/unittest/ for no-target unit suites, an
    application's flowtests/ for composed assembly flows), which are
    exactly the suites per-package coverage would drop: such a
    directory holds no code of its own, and the packages its tests
    drive from outside the package boundary would score as
    unexecuted. Measuring the suite against the whole module makes
    the number independent of where a suite lives. The merged profile
    of such a run lists each block once per test binary that ran
    (every -coverpkg fragment carries the whole module's blocks), so
    the statement census counts each distinct block once and marks it
    covered when any binary's run executed it -- go test's own merge
    concatenates fragments rather than deduplicating them, and a
    line-by-line census over the concatenation would inflate the
    total by the number of binaries that ran.
  * Measurement is cache-free by construction: the -count=1 flag makes
    go test re-run every package. This is load-bearing, not paranoia --
    go test treats -coverprofile as a cacheable test flag (the stored
    profile is replayed on a cache hit, and CI restores the go build
    cache across runs), so a run without the flag can compare a
    replayed profile against the baseline instead of the current tree
    and fail or pass on cache state alone.
  * The unit suite only: the Docker-backed integration tiers
    (-tags=integration) are not part of a coverage gate on every run.
  * The comparison carries a tolerance applied identically to both
    bounds (effective_tolerance): a measured total more than the
    effective tolerance below the 80.0% floor fails, and one more than
    it below the recorded baseline fails. The statement census is
    fixed for a fixed tree, but which blocks a suite executes is not
    perfectly stable between runs: timing-sensitive tests reach
    different block sets when scheduling shifts. The measured upper
    edge of that jitter is ~0.12 points, in go/authn's MFA
    confirm-race suite -- eight goroutines confirming one pending TOTP
    factor over SQLite, where a losing confirm either hits the
    database's write-lock error or lands a clean zero-row update
    depending on scheduler luck, so the loser-branch statements are
    covered or not by scheduling alone. The main tolerance,
    TOLERANCE_POINTS, is 0.15 points, one notch above that edge.
  * The tolerance is calibrated by the module's statement count,
    because a fixed points-tolerance is not size-invariant: in a small
    module it can sit below one statement's worth of points --
    observability's 424-statement census makes one statement worth
    about 0.24 points, more than the whole 0.15-point band, so a run
    that merely skips a statement of scheduling-sensitive coverage
    would red the gate -- while in a large module the same points
    cover several statements, looser than the intended noise budget.
    effective_tolerance is the wider of TOLERANCE_POINTS and the
    points TOLERANCE_STATEMENTS statements are worth in the module
    under measurement (TOLERANCE_STATEMENTS * 100 / total_statements):
    the 2-statement floor makes the noise budget size-invariant, and
    the main tolerance still governs modules large enough that two
    statements are worth less than it (about 1334 statements and up;
    authn's 3076-statement census keeps 0.15). The cost stays bounded
    either way: the band is about four and a half statements in
    authn's census, while a single untested function of thirty
    statements costs authn about a point -- far below any decline that
    adding code without tests produces. One tolerance, two
    comparisons, one rule. The
    recorded TOOLCHAIN (the short `go version` form) is part of the
    baseline: a check run under a different Go than the baselines were
    recorded with fails with an update instruction -- a Go upgrade
    legitimately moves coverage totals, and the honest response is
    re-measuring, not guessing.

What a breach means and how to respond

  * A PR that adds code without tests drops the total and fails one or
    both comparisons, naming the module, the measured total, the
    effective tolerance it was compared under and the breached bound
    -- the intended signal ("write the tests"). The
    same failure prints the module's largest uncovered blocks and its
    total uncovered statements, so a breach names where the gap sits,
    not only how large it is. A suite that does not merely measure low
    but goes red raises instead, with both captured streams and the
    whole-stream failure extract -- each "--- FAIL: " verdict line
    with the indented test output beneath it -- so the failing test
    and the assertion that says why stay readable from CI even when a
    long tail buries them.
  * A change that deliberately lowers coverage (removing a test whose
    scenario is obsolete, restructuring) fails the decline comparison
    and must say so: re-run with --update to record the new baseline in
    the same change that lowered it, with the reason in the commit
    message. --update cannot record a total that breaches the floor,
    though: the floor is the product decision, not a baseline, so a
    sub-floor measurement fails the floor comparison no matter what the
    baseline file says, and the honest response is adding tests (or
    revisiting the decision, which means editing LOWER_BOUND_PP and
    docs/internal/20 together). The baseline file is a committed
    artifact, so a decline never disappears silently.

Modes

  --check (default): for --module X (or every gated module with
    --all), measure and compare against both bounds. A module outside
    the gated set prints a notice and passes: the gate scope is the
    released modules, and a CI row that names anything else is not a
    module this script has a rule for.
  --update [--module X | --all]: measure and rewrite the baseline file.
    Updates only ever touch gated modules' rows; the file is written
    atomically and its rows sorted. The module's suite must be green
    for the measurement to exist at all (go test fails otherwise), and
    a sub-floor measured total refuses to be recorded (above).
  --selfcheck: verify the baseline file itself -- every row names a
    gated module whose directory exists and carries a go.mod, and
    every gated module has a row. Runs in repo-checks; a dead or
    missing row goes red before any comparison can silently skip.

Usage:
    python3 tools/check_coverage_baseline.py --check --module go/pkgcore
    python3 tools/check_coverage_baseline.py --check --all
    python3 tools/check_coverage_baseline.py --update --all
    python3 tools/check_coverage_baseline.py --selfcheck

Exit codes: 0 = clean / nothing to do; 1 = a comparison failed, a
baseline is stale or missing, or the toolchain moved; 2 = usage error.
Standard library only, Python >= 3.11. Needs a Go toolchain on PATH.
"""

