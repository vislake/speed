// TestSessionRepository_RevokeHasExactlyOneWinner covers the conditional
// update: the status is part of the WHERE clause, so a second revocation of
// the same session reports that it changed nothing.
func TestSessionRepository_RevokeHasExactlyOneWinner(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestSessionRepository(t, db)
	ctx := t.Context()
	now := time.Date(2026, 6, 1, 0, 0, 0, 0, time.UTC)

	session := &Session{UserID: "user-1", CreatedAt: now, LastSeenAt: now, ExpiresAt: now.Add(time.Hour)}
	if err := repo.Create(ctx, session); err != nil {
		t.Fatalf("Create() error = %v", err)
	}

	first, err := repo.Revoke(ctx, session.ID, RevokeReasonLogout, now)
	if err != nil {
		t.Fatalf("Revoke() error = %v", err)
	}
	if !first {
		t.Fatal("the first Revoke() reported no change")
	}

	second, err := repo.Revoke(ctx, session.ID, RevokeReasonLogout, now)
	if err != nil {
		t.Fatalf("Revoke() error = %v", err)
	}
	if second {
		t.Error("the second Revoke() reported a change; the status must be part of the WHERE clause")
	}

	stored, err := repo.FindByID(ctx, session.ID)
	if err != nil {
		t.Fatalf("FindByID() error = %v", err)
	}
	if stored.Status != SessionStatusRevoked || stored.RevokedAt == nil {
		t.Errorf("stored session = %+v, want a revoked status and a revocation timestamp", stored)
	}
}

func TestSessionRepository_SetCurrentTenantAndListByUser(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestSessionRepository(t, db)
	ctx := t.Context()
	base := time.Date(2026, 6, 1, 0, 0, 0, 0, time.UTC)

	var ids []string
	for i := range 3 {
		s := &Session{
			UserID: "user-1", CurrentTenantID: "tenant-a",
			CreatedAt: base.Add(time.Duration(i) * time.Minute), LastSeenAt: base, ExpiresAt: base.Add(time.Hour),
		}
		if err := repo.Create(ctx, s); err != nil {
			t.Fatalf("Create() error = %v", err)
		}
		ids = append(ids, s.ID)
	}
	// A session belonging to someone else must never appear in the list.
	other := &Session{UserID: "user-2", CreatedAt: base, LastSeenAt: base, ExpiresAt: base.Add(time.Hour)}
	if err := repo.Create(ctx, other); err != nil {
		t.Fatalf("Create() error = %v", err)
	}

	listed, err := repo.ListByUser(ctx, "user-1")
	if err != nil {
		t.Fatalf("ListByUser() error = %v", err)
	}
	if len(listed) != 3 {
		t.Fatalf("ListByUser() returned %d sessions, want 3", len(listed))
	}
	if listed[0].ID != ids[2] {
		t.Errorf("ListByUser()[0] = %s, want the newest session %s", listed[0].ID, ids[2])
	}

	if setErr := repo.SetCurrentTenant(ctx, ids[0], pkgcore.TenantID("tenant-b")); setErr != nil {
		t.Fatalf("SetCurrentTenant() error = %v", setErr)
	}
	stored, err := repo.FindByID(ctx, ids[0])
	if err != nil {
		t.Fatalf("FindByID() error = %v", err)
	}
	if stored.CurrentTenantID != "tenant-b" {
		t.Errorf("CurrentTenantID = %q, want %q", stored.CurrentTenantID, "tenant-b")
	}
}

// TestRefreshTokenRepository_ConsumeHasExactlyOneWinnerUnderConcurrency is the
// single-winner property replay detection rests on. Twenty goroutines race to
// consume one token; exactly one must succeed, because the loser is what the
// caller reads as a replay.
func TestRefreshTokenRepository_ConsumeHasExactlyOneWinnerUnderConcurrency(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestRefreshTokenRepository(t, db)
	ctx := t.Context()
	now := time.Date(2026, 6, 1, 0, 0, 0, 0, time.UTC)

	token := &RefreshToken{
		SessionID: "session-1", UserID: "user-1", FamilyID: "family-1",
		TokenHash: "hash-1", CreatedAt: now, ExpiresAt: now.Add(time.Hour),
	}
	if err := repo.Create(ctx, token); err != nil {
		t.Fatalf("Create() error = %v", err)
	}

	const racers = 20
	var (
		wg      sync.WaitGroup
		mu      sync.Mutex
		winners int
		failure error
	)
	wg.Add(racers)
	for range racers {
		go func() {
			defer wg.Done()
			won, err := repo.Consume(ctx, token.ID, now)
			mu.Lock()
			defer mu.Unlock()
			if err != nil {
				failure = err
				return
			}
			if won {
				winners++
			}
		}()
	}
	wg.Wait()

	if failure != nil {
		t.Fatalf("Consume() error = %v", failure)
	}
	if winners != 1 {
		t.Fatalf("Consume() reported %d winners across %d concurrent calls, want exactly 1", winners, racers)
	}

	stored, err := repo.FindByHash(ctx, "hash-1")
	if err != nil {
		t.Fatalf("FindByHash() error = %v", err)
	}
	if stored.Status != RefreshTokenStatusRotated || stored.ConsumedAt == nil {
		t.Errorf("stored token = %+v, want a rotated status and a consumption timestamp", stored)
	}
}

func TestRefreshTokenRepository_RevokeFamilyAndBySession(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestRefreshTokenRepository(t, db)
	ctx := t.Context()
	now := time.Date(2026, 6, 1, 0, 0, 0, 0, time.UTC)

	mk := func(hash, family, session string) *RefreshToken {
		token := &RefreshToken{
			SessionID: session, UserID: "user-1", FamilyID: family,
			TokenHash: hash, CreatedAt: now, ExpiresAt: now.Add(time.Hour),
		}
		if err := repo.Create(ctx, token); err != nil {
			t.Fatalf("Create(%s) error = %v", hash, err)
		}
		return token
	}
	mk("h1", "family-1", "session-1")
	mk("h2", "family-1", "session-1")
	untouched := mk("h3", "family-2", "session-2")

	revoked, err := repo.RevokeFamily(ctx, "family-1", now)
	if err != nil {
		t.Fatalf("RevokeFamily() error = %v", err)
	}
	if revoked != 2 {
		t.Errorf("RevokeFamily() revoked %d tokens, want 2", revoked)
	}

	stored, err := repo.FindByHash(ctx, "h3")
	if err != nil {
		t.Fatalf("FindByHash() error = %v", err)
	}
	if stored.Status != RefreshTokenStatusActive {
		t.Errorf("an unrelated family's token was revoked: %+v", stored)
	}

	if _, revokeErr := repo.RevokeBySession(ctx, untouched.SessionID, now); revokeErr != nil {
		t.Fatalf("RevokeBySession() error = %v", revokeErr)
	}
	stored, err = repo.FindByHash(ctx, "h3")
	if err != nil {
		t.Fatalf("FindByHash() error = %v", err)
	}
	if stored.Status != RefreshTokenStatusRevoked {
		t.Errorf("Status = %q, want %q after RevokeBySession", stored.Status, RefreshTokenStatusRevoked)
	}
}

func TestLoginAttemptRepository_ListByUserIsNewestFirstAndBounded(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestLoginAttemptRepository(t, db)
	ctx := t.Context()
	base := time.Date(2026, 6, 1, 0, 0, 0, 0, time.UTC)

	for i := range 5 {
		attempt := &LoginAttempt{
			UserID: "user-1", Method: MethodPassword, Result: LoginResultFailure,
			FailureReason: FailureReasonBadPassword,
			CreatedAt:     base.Add(time.Duration(i) * time.Minute),
		}
		if err := repo.Create(ctx, attempt); err != nil {
			t.Fatalf("Create() error = %v", err)
		}
	}
	if err := repo.Create(ctx, &LoginAttempt{
		UserID: "user-2", Method: MethodPassword, Result: LoginResultSuccess, CreatedAt: base,
	}); err != nil {
		t.Fatalf("Create() error = %v", err)
	}

	listed, err := repo.ListByUser(ctx, "user-1", 3)
	if err != nil {
		t.Fatalf("ListByUser() error = %v", err)
	}
	if len(listed) != 3 {
		t.Fatalf("ListByUser(limit 3) returned %d rows, want 3", len(listed))
	}
	if !listed[0].CreatedAt.After(listed[2].CreatedAt) {
		t.Error("ListByUser() is not newest-first")
	}
	for _, attempt := range listed {
		if attempt.UserID != "user-1" {
			t.Errorf("ListByUser() returned another user's attempt: %+v", attempt)
		}
	}

	all, err := repo.ListByUser(ctx, "user-1", 0)
	if err != nil {
		t.Fatalf("ListByUser(no limit) error = %v", err)
	}
	if len(all) != 5 {
		t.Errorf("ListByUser(no limit) returned %d rows, want all 5 under the default bound", len(all))
	}
}

