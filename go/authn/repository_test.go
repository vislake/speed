func TestUserRepository_CreateAndFindByID(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestUserRepository(t, db)
	ctx := t.Context()

	user := &User{Email: "round.trip@example.com", DisplayName: "Round Trip", PasswordHash: "hash"}
	if err := repo.Create(ctx, user); err != nil {
		t.Fatalf("Create() error = %v", err)
	}
	if user.ID == "" {
		t.Fatal("Create() left the ID empty; ids are generated by the application")
	}

	got, err := repo.FindByID(ctx, user.ID)
	if err != nil {
		t.Fatalf("FindByID() error = %v", err)
	}
	if got.Email != user.Email || got.DisplayName != "Round Trip" {
		t.Errorf("FindByID() = %+v, want the created user", got)
	}
	if got.Status != UserStatusActive {
		t.Errorf("Status = %q, want %q by default", got.Status, UserStatusActive)
	}

	if _, err := repo.FindByID(ctx, "no-such-id"); !errors.Is(err, ErrNotFound) {
		t.Errorf("FindByID(missing) error = %v, want ErrNotFound", err)
	}
}

// TestUserRepository_FindByEmail_IsSpellingInsensitive is the whole point of
// the blind index: the address is encrypted, so no query can filter on it,
// yet an exact lookup still has to work regardless of how the address was
// typed.
func TestUserRepository_FindByEmail_IsSpellingInsensitive(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestUserRepository(t, db)
	ctx := t.Context()

	user := &User{Email: "Casing.Matters@Example.COM", PasswordHash: "hash"}
	if err := repo.Create(ctx, user); err != nil {
		t.Fatalf("Create() error = %v", err)
	}

	for _, spelling := range []string{
		"Casing.Matters@Example.COM",
		"casing.matters@example.com",
		"  casing.matters@EXAMPLE.com  ",
		"CASING.MATTERS@EXAMPLE.COM",
	} {
		got, err := repo.FindByEmail(ctx, spelling)
		if err != nil {
			t.Fatalf("FindByEmail(%q) error = %v", spelling, err)
		}
		if got.ID != user.ID {
			t.Errorf("FindByEmail(%q) found %s, want %s", spelling, got.ID, user.ID)
		}
	}

	if _, err := repo.FindByEmail(ctx, "someone.else@example.com"); !errors.Is(err, ErrNotFound) {
		t.Errorf("FindByEmail(unknown) error = %v, want ErrNotFound", err)
	}
}

// TestUserRepository_FindByPhone_IsFormattingInsensitive is the same property
// for phone numbers, whose canonical form is E.164.
func TestUserRepository_FindByPhone_IsFormattingInsensitive(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestUserRepository(t, db)
	ctx := t.Context()

	user := &User{Phone: "+86 138 0000 0000", PasswordHash: "hash"}
	if err := repo.Create(ctx, user); err != nil {
		t.Fatalf("Create() error = %v", err)
	}

	for _, spelling := range []string{
		"+86 138 0000 0000",
		"+8613800000000",
		"+86-138-0000-0000",
		"+86(138)0000.0000",
	} {
		got, err := repo.FindByPhone(ctx, spelling)
		if err != nil {
			t.Fatalf("FindByPhone(%q) error = %v", spelling, err)
		}
		if got.ID != user.ID {
			t.Errorf("FindByPhone(%q) found %s, want %s", spelling, got.ID, user.ID)
		}
	}

	// A bare national number has no E.164 canonical form -- dbkit's
	// normalizer refuses to guess a country -- so it is reported as an
	// invalid phone rather than silently indexed under a wrong country.
	if _, err := repo.FindByPhone(ctx, "13800000000"); !hasCode(err, ErrInvalidPhone.Code) {
		t.Errorf("FindByPhone(national form) error = %v, want code %q", err, ErrInvalidPhone.Code)
	}
}

// TestUserRepository_DuplicateIdentifierIsRejectedByTheDatabase proves the
// UNIQUE index is on the blind index, which is what makes "one account per
// real-world address" true rather than "one account per spelling".
func TestUserRepository_DuplicateIdentifierIsRejectedByTheDatabase(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestUserRepository(t, db)
	ctx := t.Context()

	if err := repo.Create(ctx, &User{Email: "unique@example.com", PasswordHash: "hash"}); err != nil {
		t.Fatalf("Create() error = %v", err)
	}
	// A different spelling of the same address must still collide.
	if err := repo.Create(ctx, &User{Email: "UNIQUE@Example.com", PasswordHash: "hash"}); err == nil {
		t.Fatal("a second account with the same address in a different casing was accepted")
	}
}

