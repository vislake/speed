// TestUserRepository_SaveRecomputesTheIndex proves a changed address cannot
// leave a stale index behind, which would leave the account findable under
// its old address and not under its new one.
func TestUserRepository_SaveRecomputesTheIndex(t *testing.T) {
	t.Parallel()

	db := testutil.NewDB(t)
	repo := newTestUserRepository(t, db)
	ctx := t.Context()

	user := &User{Email: "before@example.com", PasswordHash: "hash"}
	if err := repo.Create(ctx, user); err != nil {
		t.Fatalf("Create() error = %v", err)
	}

	user.Email = "after@example.com"
	if err := repo.Save(ctx, user); err != nil {
		t.Fatalf("Save() error = %v", err)
	}

	if _, err := repo.FindByEmail(ctx, "before@example.com"); !errors.Is(err, ErrNotFound) {
		t.Errorf("the old address still finds the account: err = %v", err)
	}
	got, err := repo.FindByEmail(ctx, "after@example.com")
	if err != nil {
		t.Fatalf("FindByEmail(new address) error = %v", err)
	}
	if got.ID != user.ID {
		t.Errorf("FindByEmail(new address) found %s, want %s", got.ID, user.ID)
	}
}

